/**
 * Turn the 50m countries topology into a compact coastline point set for the
 * hero globe.
 *
 * The topology is 756KB and the globe needs points, not polygons — shipping
 * the whole thing to the browser to draw dots would be most of a megabyte for
 * a decoration. This decodes the delta-encoded arcs once, at build time,
 * thins them to a fixed spacing, and writes a flat array the canvas can spin
 * without any geometry work at runtime.
 *
 *   node scripts/make-coastline.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";

const SRC = "public/geo/countries-50m.json";
const OUT = "lib/coastline.ts";
/** Degrees between kept points along an arc. Smaller is denser and heavier. */
const SPACING = 1.1;

const topo = JSON.parse(readFileSync(SRC, "utf8"));
const [sx, sy] = topo.transform.scale;
const [tx, ty] = topo.transform.translate;

/** TopoJSON arcs are delta-encoded in quantised integer space. */
function decode(arc) {
  let x = 0, y = 0;
  const out = [];
  for (const [dx, dy] of arc) {
    x += dx; y += dy;
    out.push([x * sx + tx, y * sy + ty]); // lon, lat
  }
  return out;
}

const kept = [];
let last = null;

for (const arc of topo.arcs) {
  last = null;
  for (const [lon, lat] of decode(arc)) {
    if (lat < -60) continue;           // Antarctica is a white band at this size
    if (last) {
      const d = Math.hypot(lon - last[0], (lat - last[1]) * 1.2);
      if (d < SPACING) continue;
    }
    // One decimal is ~11km — finer than a 2px dot on a 300px globe can show.
    kept.push([Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]);
    last = [lon, lat];
  }
}

// Identical points are common where arcs meet at shared borders.
const seen = new Set();
const uniq = kept.filter(([a, b]) => {
  const k = `${a},${b}`;
  if (seen.has(k)) return false;
  seen.add(k);
  return true;
});

const body = uniq.map(([a, b]) => `${a},${b}`).join(",");
writeFileSync(OUT, `/**
 * Coastline points for the hero globe — lon,lat pairs, flat.
 *
 * GENERATED by scripts/make-coastline.mjs from public/geo/countries-50m.json.
 * Do not edit: re-run the script instead. Flat rather than nested so the
 * array is one allocation and the source file stays a fraction of the size.
 */
export const COAST: number[] = [${body}];
`);

console.log(`arcs ${topo.arcs.length} -> points ${uniq.length}, ${(Buffer.byteLength(body) / 1024).toFixed(0)}KB`);
